let language = 'es';
export function chooseLanguage(search = '', storage, navigatorLanguage = '') {
  const candidate = new URLSearchParams(search).get('lang');
  if (candidate === 'es' || candidate === 'en') return candidate;
  let saved;
  try { saved = storage?.getItem('lang'); } catch { /* storage may be disabled */ }
  if (saved === 'es' || saved === 'en') return saved;
  return /^en\b|^en[-_]/i.test(navigatorLanguage) ? 'en' : 'es';
}
export function setLanguage(next) { language = next === 'en' ? 'en' : 'es'; return language; }
export function getLanguage() { return language; }
export function t(key, params = {}) {
  const value = dictionaries[language][key];
  if (value === undefined) return key;
  return value.replace(/\{([\w]+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
export function formatNumber(value, digits = 1) {
  return new Intl.NumberFormat(language === 'en' ? 'en-US' : 'es-MX', { maximumFractionDigits: digits }).format(value);
}
export function formatDate(iso) {
  const parts = new Intl.DateTimeFormat(language === 'en' ? 'en-US' : 'es-MX', { day:'numeric', month:'short', year:'numeric', hour:'2-digit', minute:'2-digit', hourCycle:'h23', timeZone:'UTC' }).formatToParts(new Date(iso));
  const get = type => parts.find(part => part.type === type)?.value ?? '';
  const month = get('month').replace(/\.$/, '');
  return language === 'en' ? `${month} ${get('day')}, ${get('year')}, ${get('hour')}:${get('minute')} UTC` : `${get('day')} ${month} ${get('year')}, ${get('hour')}:${get('minute')} UTC`;
}
function dayParts(iso) {
  const parts = new Intl.DateTimeFormat(language === 'en' ? 'en-US' : 'es-MX', { day:'numeric', month:'short', year:'numeric', hour:'2-digit', minute:'2-digit', hourCycle:'h23', timeZone:'UTC' }).formatToParts(new Date(iso));
  const get = type => parts.find(part => part.type === type)?.value ?? '';
  return { day: get('day'), month: get('month').replace(/\.$/, ''), year: get('year'), time: `${get('hour')}:${get('minute')}` };
}
export function formatDay(isoDate) {
  const p = dayParts(`${isoDate}T12:00:00Z`);
  return language === 'en' ? `${p.month} ${p.day}, ${p.year}` : `${p.day} ${p.month} ${p.year}`;
}
export function formatClock(iso) {
  const p = dayParts(iso);
  return language === 'en' ? `${p.month} ${p.day} · ${p.time} UTC` : `${p.day} ${p.month} · ${p.time} UTC`;
}
